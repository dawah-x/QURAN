#!/usr/bin/env python3
"""Regenerate Bengali Tafseer ibn Kathir lazy shards from the verbatim snapshot.

    python3 tools/build-tafsir-ibn-kathir.py

Source: data/tafsir_ibn_kathir_bn.json.gz — QUL resource 31 JSON export,
retrieved through spa5k/tafsir_api (MIT code). See
LICENSES/qul-ibn-kathir-source-note.txt and CREDITS.md §9.

Outputs (deterministic):
  assets/tafsir-ibn-kathir-index.js   tiny boot metadata
  assets/tafsir-ibn-kathir/<s>.js     one lazy shard per surah (1..114)

The QUL export repeats one commentary passage for every ayah in its range.
Only 1,914 of the 6,236 entries are unique, so each shard stores a local
`texts` array plus an `ayah`-indexed `map` of integers. No text is edited:
window.BN_TAFSIR_IBN_KATHIR['<s>'] = {t:[...], m:[...]}.
"""
from __future__ import annotations

import gzip
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "data/tafsir_ibn_kathir_bn.json.gz"
OUT = ROOT / "assets" / "tafsir-ibn-kathir"
VERSION = "11"


def main() -> None:
    snap = json.loads(gzip.decompress(SNAPSHOT.read_bytes()).decode("utf-8"))
    surahs = snap["surahs"]
    assert set(surahs) == {str(i) for i in range(1, 115)}, "114 surahs required"
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.js"):
        old.unlink()

    meta = {
        "version": VERSION,
        "name": "তাফসীর ইবনে কাসীর (বাংলা)",
        "source": snap["source"],
        "author": snap["author"],
        "viaRepository": snap["viaRepository"],
        "licenseNote": snap["viaLicense"],
        "note": snap["note"],
        "format": "dedup",
        "surahs": {},
    }
    total = unique = 0
    for s in range(1, 115):
        arr = surahs[str(s)]
        assert isinstance(arr, list) and arr, f"surah {s}"
        texts, index, seen = [], [], {}
        for x in arr:
            t = x["text"]
            if t not in seen:
                seen[t] = len(texts)
                texts.append(t)
            index.append(seen[t])
        total += len(arr)
        unique += len(texts)
        meta["surahs"][str(s)] = {"ayahs": len(arr), "texts": len(texts)}
        payload = json.dumps(
            {"t": texts, "m": index}, ensure_ascii=False, separators=(",", ":"))
        text = (
            "/* DAWAH X — বাংলা তাফসীর ইবনে কাসীর, সূরা %d · %d আয়াত / %d অনুচ্ছেদ · "
            "QUL resource 31 via spa5k/tafsir_api · see CREDITS.md */\n"
            "window.BN_TAFSIR_IBN_KATHIR['%d']=%s;\n"
            % (s, len(arr), len(texts), s, payload)
        )
        (OUT / f"{s}.js").write_text(text, encoding="utf-8")

    head = (
        "/* DAWAH X — Bengali Tafseer ibn Kathir index (v%s). Generated by\n"
        "   tools/build-tafsir-ibn-kathir.py; do not edit by hand. */\n"
        "window.BN_TAFSIR_IBN_KATHIR={};\n"
        "window.TAFSIR_IBN_KATHIR_INDEX=%s;\n"
        % (VERSION, json.dumps(meta, ensure_ascii=False, separators=(",", ":")))
    )
    (ROOT / "assets" / "tafsir-ibn-kathir-index.js").write_text(head, encoding="utf-8")
    print("tafsir-ibn-kathir: 114 shards, %d ayah entries, %d unique passages" % (
        total, unique))


if __name__ == "__main__":
    main()
