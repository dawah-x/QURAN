#!/usr/bin/env python3
"""Generate assets/quran-meta.js from the vendored Hafs metadata snapshot.

Source: quran-meta v7.0.0 (MIT), https://github.com/quran-center/quran-meta
        npm tarball https://registry.npmjs.org/quran-meta/-/quran-meta-7.0.0.tgz
        data/quran-meta-hafs.json is a verbatim dump of the `HafsLists` export
        (JuzList, PageList, HizbQuarterList, RukuList, ManzilList, SajdaList,
        SurahList). LICENSES/quran-meta-MIT.txt holds the license.

List format (all numbers are 1-based *global ayah ids*, except the leading 0
and the trailing 6237 sentinel):
  JuzList[k]          global ayah id where juz k starts (k = 1..30)
  PageList[k]         global ayah id where Madinah Mushaf page k starts (1..604)
  HizbQuarterList[k]  global ayah id where hizb-quarter k starts (1..240)
  RukuList[k], ManzilList[k], SajdaList (ayah ids of the 15 sajda verses)
  SurahList[n] = [firstAyahId, ayahCount, revelationOrder, rukuCount,
                  arabicName, isMeccan]   (n = 1..114; index 0 and 115 are sentinels)

The site's own QURAN/FLAT array is sequential 1..6236, so global ayah id == array index + 1.

  python3 tools/build-meta.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data/quran-meta-hafs.json"
OUT = ROOT / "assets/quran-meta.js"


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    # Keep only what the UI needs; the JSON stays verbatim in data/.
    payload = {
        "source": "quran-meta v7.0.0 (MIT) · Hafs riwaya",
        "juz": d["JuzList"][1:31],              # 30 juz starts
        "page": d["PageList"][1:605],           # 604 page starts
        "hizbQuarter": d["HizbQuarterList"][1:241],
        "ruku": d["RukuList"][1:-1],
        "manzil": d["ManzilList"][1:-1],
        "sajda": d["SajdaList"],
        "surah": [
            {"order": row[2], "rukus": row[3], "makki": bool(row[5])}
            for row in d["SurahList"][1:115]
        ],
        "end": 6237,
    }
    assert len(payload["juz"]) == 30
    assert len(payload["page"]) == 604
    assert len(payload["surah"]) == 114
    assert payload["juz"][0] == 1 and payload["page"][0] == 1

    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "/* Generated by tools/build-meta.py — DO NOT EDIT.\n"
        "   Source: quran-meta v7.0.0 (MIT), Hafs metadata.\n"
        "   See CREDITS.md and LICENSES/quran-meta-MIT.txt. */\n"
        "window.QURAN_META = " + body + ";\n",
        encoding="utf-8",
    )
    print(f"OK: {OUT.relative_to(ROOT)} — {OUT.stat().st_size:,} bytes, "
          f"30 juz / 604 pages / 114 surahs")


if __name__ == "__main__":
    main()
